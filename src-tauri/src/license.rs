/// License system - Ed25519 signed keys + a TRIAL_DAYS-day trial.
///
/// Key format:  <base64url_message>.<base64url_64_byte_signature>
/// Message:     "v1:{email}:{plan}:{iat}:{exp}"   (UTF-8, exp=0 means lifetime)
///
/// After first activation the decoded data is written to:
///   <app_data_dir>/license.json
///
/// Trial is tracked in TWO locations (8 LE bytes = u64 unix timestamp of first launch):
///   <app_data_dir>/.trial        - removed on a full uninstall
///   <home>/.stroke/trial         - survives uninstall, so reinstalling does NOT
///                                  grant a fresh trial. The earliest timestamp
///                                  across both wins, and both are repaired on read.
///   (For tamper-proof enforcement across full disk wipes, register the trial
///    start server-side keyed by device_id - the API scaffolding already exists.)
///
/// -------------------------------------------------------------------
/// SETUP: run  `node scripts/license-tool.mjs keygen`  once.
/// Copy the printed public key hex into PUBLIC_KEY_HEX below, then rebuild.
/// -------------------------------------------------------------------
use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine as _};
use ed25519_dalek::{Signature, Verifier, VerifyingKey};
use sha2::{Digest, Sha256};
use std::{
    path::{Path, PathBuf},
    time::{SystemTime, UNIX_EPOCH},
};

const STROKE_API: &str = "https://stroke.click/api/license";

// ── Generated by `node scripts/license-tool.mjs keygen` ─────────────────────
pub const PUBLIC_KEY_HEX: &str =
    "b5f14fed4694302a767e32c4e6a50ba0074c4e50f5198ad781de00d0e8ba8771";

pub const TRIAL_DAYS: i64 = 17;
const LICENSE_FILE: &str = "license.json";
const TRIAL_FILE: &str = ".trial";

// ── Revocation list ───────────────────────────────────────────────────────────
// Each entry is the hex-encoded SHA-256 of the full license key string.
// To revoke a key:
//   1. Run: node scripts/license-tool.mjs revoke <KEY>
//   2. Copy the printed hash into this array.
//   3. Rebuild and ship an app update.
//
// Note: revocation only takes effect after the user installs the update.
// For immediate remote revocation you'll need the server endpoint (coming later).
const REVOKED_KEY_HASHES: &[&str] = &[
    "ed13c9edc3bea01c6f82a415a10b21f85b85f829004f473cb78e8cd10056059f", // revoked 2026-06-05 (case: LIC-REV-2026-06-05-01)
];

